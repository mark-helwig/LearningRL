@configclass
class LearningRLG1WalkEnvCfg(ManagerBasedRLEnvCfg):
    """Configuration for the locomotion velocity-tracking environment."""

    # Simulation settings
    sim: SimulationCfg = SimulationCfg(physics=PhysicsCfg())
    # Viewer
    viewer = ViewerCfg(eye=(2.8, -0.5, 0.7), origin_type="asset_root", env_index=0, asset_name="robot")
    # Scene settings
    scene: SceneCfg = SceneCfg(num_envs=4096, env_spacing=2.5)
    # Basic settings
    observations: ObservationsCfg = ObservationsCfg()
    actions: ActionsCfg = ActionsCfg()
    commands: CommandsCfg = CommandsCfg()
    # MDP settings
    rewards: RewardsCfg = RewardsCfg()
    terminations: TerminationsCfg = TerminationsCfg()
    events: EventCfg = EventCfg()

    def __post_init__(self) -> None:
        """Post initialization."""
        # general settings
        self.decimation = 4
        self.episode_length_s = 20.0
        # simulation settings
        self.sim.dt = 0.005
        self.sim.render_interval = self.decimation
        self.sim.physics_material = self.scene.terrain.physics_material

        # sensors from robot_description; one fresh entity_cfg() per term, since resolution mutates it
        G1_FEET_CONTACT.attach(self.scene)
        G1_TERMINATION_CONTACT.attach(self.scene)
        # history 1, physics-rate ticks, and a 1 N contact switch match the old catch-all sensor
        for sensor in (self.scene.g1_feet, self.scene.g1_termination):
            sensor.history_length = 1
            sensor.update_period = self.sim.dt
        self.scene.g1_feet.force_threshold = 1.0


